export const STRINGS: Record<Lang, Record<string, string>> = { es: ES, en: EN };

const STORAGE_KEY = 'quadra-lang';

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<Lang>(this.initial());

  setLang(lang: Lang): void {
    this.lang.set(lang);
    localStorage.setItem(STORAGE_KEY, lang);
  }

  toggle(): void {
    this.setLang(this.lang() === 'es' ? 'en' : 'es');
  }

  t(key: string, params?: Record<string, string | number | null>): string {
    let s = STRINGS[this.lang()][key] ?? ES[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replaceAll(`{${k}}`, String(v ?? ''));
      }
    }
    return s;
  }

  private initial(): Lang {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'en' || saved === 'es' ? saved : 'es';
  }
}

@Pipe({ name: 't', standalone: true, pure: false })
export class TranslatePipe implements PipeTransform {
  private readonly i18n = inject(I18nService);

  transform(key: string, params?: Record<string, string | number | null>): string {
    return this.i18n.t(key, params);
  }
}
